export const crawlerHelperMessages = { en, zh };

export const defaultCrawlerTranslator: CrawlerTranslator = (key, params) => {
  const prefix = "crawlerHelpers.";
  const messageKey = key.startsWith(prefix) ? key.slice(prefix.length) : "";
  const template = Object.prototype.hasOwnProperty.call(en, messageKey)
    ? en[messageKey as keyof typeof en]
    : key;
  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) => (
    params && Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : placeholder
  ));
};
